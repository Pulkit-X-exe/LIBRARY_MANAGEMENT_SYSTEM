async function seed200Books() {
  console.log('📚 Starting realistic 200-book catalogue generation for Adarsh Senior Secondary School...');

  const catalogue = generateComplete200Catalogue();
  console.log(`Prepared catalogue list of ${catalogue.length} books.`);

  // 1. Gather all unique categories, subjects, authors, publishers
  const catNames = [...new Set(catalogue.map(b => b.category))];
  const subNames = [...new Set(catalogue.map(b => b.subject))];
  const authNames = [...new Set(catalogue.map(b => b.author))];
  const pubNames = [...new Set(catalogue.map(b => b.publisher))];

  // 2. Ensure Categories exist
  const catMap = {};
  for (const name of catNames) {
    let [cat] = await Category.findOrCreate({
      where: { name },
      defaults: { code: name.slice(0, 4).toUpperCase(), description: `${name} literature & academic references` }
    });
    catMap[name] = cat.id;
  }

  // 3. Ensure Subjects exist
  const subMap = {};
  for (const name of subNames) {
    let [sub] = await Subject.findOrCreate({
      where: { name },
      defaults: { code: name.slice(0, 4).toUpperCase() }
    });
    subMap[name] = sub.id;
  }

  // 4. Ensure Authors exist
  const authMap = {};
  for (const name of authNames) {
    let [auth] = await Author.findOrCreate({
      where: { name },
      defaults: { biography: `Celebrated academic author and contributor in education.` }
    });
    authMap[name] = auth.id;
  }

  // 5. Ensure Publishers exist
  const pubMap = {};
  for (const name of pubNames) {
    let [pub] = await Publisher.findOrCreate({
      where: { name },
      defaults: { address: 'New Delhi / Gurugram, India', contact: 'editorial@schoolpublisher.edu.in' }
    });
    pubMap[name] = pub.id;
  }

  // Ensure Books columns exist before insertion
  const queryInterface = sequelize.getQueryInterface();
  const { DataTypes } = require('sequelize');
  const booksTable = await queryInterface.describeTable('Books').catch(() => null);
  if (booksTable) {
    if (!booksTable.issued_copies) await queryInterface.addColumn('Books', 'issued_copies', { type: DataTypes.INTEGER, defaultValue: 0 }).catch(() => {});
    if (!booksTable.reserved_copies) await queryInterface.addColumn('Books', 'reserved_copies', { type: DataTypes.INTEGER, defaultValue: 0 }).catch(() => {});
    if (!booksTable.pages) await queryInterface.addColumn('Books', 'pages', { type: DataTypes.INTEGER, defaultValue: 250 }).catch(() => {});
    if (!booksTable.condition) await queryInterface.addColumn('Books', 'condition', { type: DataTypes.STRING, defaultValue: 'Good' }).catch(() => {});
    if (!booksTable.borrow_count) await queryInterface.addColumn('Books', 'borrow_count', { type: DataTypes.INTEGER, defaultValue: 0 }).catch(() => {});
    if (!booksTable.short_summary) await queryInterface.addColumn('Books', 'short_summary', { type: DataTypes.TEXT, allowNull: true }).catch(() => {});
  }

  // 6. Delete any old books that don't match or clean up Book table before inserting clean 200
  // Note: We clean BookCopy and Book to start with fresh 200 pristine catalogue items
  await BookCopy.destroy({ where: {} });
  await Book.destroy({ where: {} });

  console.log('Inserting 200 books into database...');

  for (let i = 0; i < catalogue.length; i++) {
    const item = catalogue[i];
    const category_id = catMap[item.category] || null;
    const subject_id = subMap[item.subject] || null;
    const author_id = authMap[item.author] || null;
    const publisher_id = pubMap[item.publisher] || null;

    const coverUrl = coverImageMap[item.subject] || "https://images.unsplash.com/photo-1544716278-ca5e3f4abd8c?auto=format&fit=crop&w=600&q=80";

    const totalCopies = item.copies || 4;
    const issuedCopies = item.issued || 0;
    const reservedCopies = item.reserved || 0;
    const availableCopies = Math.max(0, totalCopies - issuedCopies - reservedCopies);

    const book = await Book.create({
      id: i + 1,
      isbn: item.isbn,
      title: item.title,
      category_id,
      subject_id,
      author_id,
      publisher_id,
      edition: item.edition,
      publication_year: item.year,
      language: item.language,
      description: item.description,
      short_summary: item.description.slice(0, 160) + '...',
      cover_image: coverUrl,
      total_copies: totalCopies,
      available_copies: availableCopies,
      issued_copies: issuedCopies,
      reserved_copies: reservedCopies,
      shelf_number: item.shelf,
      rack_number: item.rack,
      row_number: 'Row ' + ((i % 3) + 1),
      condition: item.condition,
      pages: item.pages,
      borrow_count: item.borrow_count,
      price: item.price,
      status: availableCopies > 0 ? 'available' : (issuedCopies > 0 ? 'issued' : 'reserved')
    });

    // Create corresponding physical BookCopy records
    const copiesToCreate = [];
    for (let c = 1; c <= totalCopies; c++) {
      let copyStatus = 'available';
      if (c <= issuedCopies) copyStatus = 'issued';
      else if (c <= issuedCopies + reservedCopies) copyStatus = 'reserved';

      copiesToCreate.push({
        book_id: book.id,
        barcode: `ADARSH-LIB-${String(book.id).padStart(4, '0')}-C${c}`,
        condition: item.condition === 'Fair' ? 'fair' : (item.condition === 'Needs Repair' ? 'damaged' : 'good'),
        status: copyStatus
      });
    }
    await BookCopy.bulkCreate(copiesToCreate);
  }

  const finalCount = await Book.count();
  const copyCount = await BookCopy.count();
  console.log(`✅ Seeding complete! Total Books in DB: ${finalCount}, Total Physical Copies: ${copyCount}`);
}

